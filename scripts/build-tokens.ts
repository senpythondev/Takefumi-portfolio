/**
 * Generates the CSS and the token list from src/styles/tokens.ts (the single source).
 *
 *   node scripts/build-tokens.ts           write src/styles/tokens.generated.css and docs/DESIGN_TOKENS.md
 *   node scripts/build-tokens.ts --check   fail if either is stale or the palette breaks its rules
 *                                          (part of `npm run validate`)
 *
 * Rules checked: every colour is #rrggbb; neighbouring layer colours differ by at least
 * LAYER_NEIGHBOUR_MIN_CONTRAST; body text keeps WCAG AA (4.5:1) on the backgrounds.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { base, city, confidence, font, layer, LAYER_NEIGHBOUR_MIN_CONTRAST, motion, signal, space } from '../src/styles/tokens.ts';

const ROOT = new URL('..', import.meta.url).pathname;
const CSS_PATH = 'src/styles/tokens.generated.css';
const DOC_PATH = 'docs/DESIGN_TOKENS.md';
const CHECK = process.argv.includes('--check');

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function luminance(hex: string): number {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const v = parseInt(hex.slice(i, i + 2), 16) / 255;
    return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  }) as [number, number, number];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

const problems: string[] = [];
const colours: Record<string, string> = {
  ...Object.fromEntries(Object.entries(base).map(([k, v]) => [kebab(k), v])),
  ...Object.fromEntries(Object.entries(signal).map(([k, v]) => [k, v])),
  approx: confidence.approx,
  reconstructed: confidence.reconstructed,
  ...Object.fromEntries(Object.entries(layer).map(([k, v]) => [`layer-${k}`, v])),
  ...Object.fromEntries(Object.entries(city).map(([k, v]) => [`city-${kebab(k)}`, v])),
};
for (const [name, value] of Object.entries(colours)) if (!/^#[0-9a-f]{6}$/.test(value)) problems.push(`colour ${name} must be #rrggbb, got ${value}`);

const layers = Object.entries(layer);
const neighbours = layers.slice(0, -1).map(([id, hex], i) => {
  const [nextId, nextHex] = layers[i + 1] as [string, string];
  const ratio = contrast(hex, nextHex);
  if (ratio < LAYER_NEIGHBOUR_MIN_CONTRAST) problems.push(`layer ${id} → ${nextId}: contrast ${ratio.toFixed(2)} < ${LAYER_NEIGHBOUR_MIN_CONTRAST}`);
  return { id, nextId, ratio };
});
for (const bg of ['ground', 'stratum'] as const) {
  for (const fg of ['ink', 'inkMuted'] as const) {
    const ratio = contrast(base[fg], base[bg]);
    if (ratio < 4.5) problems.push(`text ${fg} on ${bg}: ${ratio.toFixed(2)} < 4.5`);
  }
}

const header = '/* Generated by scripts/build-tokens.ts from src/styles/tokens.ts — do not edit. */';
const css = `${header}
@theme {
${Object.entries(colours)
  .map(([k, v]) => `  --color-${k}: ${v};`)
  .join('\n')}
  --font-sans: ${font.sans.join(', ')};
  --font-mono: ${font.mono.join(', ')};
${Object.entries(motion.ease)
  .map(([k, v]) => `  --ease-${k}: ${v};`)
  .join('\n')}
}

:root {
  --gutter: ${space.gutter};
  --measure: ${space.measure};
${Object.entries(motion.duration)
  .map(([k, v]) => `  --duration-${k}: ${v};`)
  .join('\n')}
}
`;

const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
const doc = `# デザイントークン

> \`scripts/build-tokens.ts\` が \`src/styles/tokens.ts\` から生成する。手で編集しない（\`npm run tokens\`）。
> コントラスト比は WCAG の相対輝度による。

## ベースと文字
${row(['名前', '値', '地色 ground との比', 'stratum との比'])}
${row(['---', '---', '---', '---'])}
${Object.entries(base)
  .map(([k, v]) => row([k, `\`${v}\``, contrast(v, base.ground).toFixed(2), contrast(v, base.stratum).toFixed(2)]))
  .join('\n')}

## 信号色（光る・強調するときだけ。地層の色には使わない）
${row(['名前', '値', 'ground との比'])}
${row(['---', '---', '---'])}
${Object.entries(signal)
  .map(([k, v]) => row([k, `\`${v}\``, contrast(v, base.ground).toFixed(2)]))
  .join('\n')}

## 確度ラベル
${row(['確度', '表示名', '値', 'ground との比'])}
${row(['---', '---', '---', '---'])}
${row(['measured', '確認済み／Verified', `\`${confidence.measured}\``, contrast(confidence.measured, base.ground).toFixed(2)])}
${row(['approx', '概算／Approx.', `\`${confidence.approx}\``, contrast(confidence.approx, base.ground).toFixed(2)])}
${row(['reconstructed', '再現／Reconstructed', `\`${confidence.reconstructed}\``, contrast(confidence.reconstructed, base.ground).toFixed(2)])}

## 地層（上から順。隣同士のコントラスト比は ${LAYER_NEIGHBOUR_MIN_CONTRAST} 以上）
${row(['地層', '値', '次の地層との比'])}
${row(['---', '---', '---'])}
${layers.map(([id, v], i) => row([id, `\`${v}\``, neighbours[i] ? neighbours[i].ratio.toFixed(2) : '—'])).join('\n')}

## 都市（地層4）
${row(['名前', '値'])}
${row(['---', '---'])}
${Object.entries(city)
  .map(([k, v]) => row([k, `\`${v}\``]))
  .join('\n')}

## 書体・余白・動き
- 本文：\`${font.sans.join(', ')}\`
- 等幅：\`${font.mono.join(', ')}\`
- 余白：gutter \`${space.gutter}\`、本文の幅 \`${space.measure}\`
- イージング：${Object.entries(motion.ease)
  .map(([k, v]) => `${k} \`${v}\``)
  .join('、')}
- 時間：${Object.entries(motion.duration)
  .map(([k, v]) => `${k} ${v}`)
  .join('、')}
`;

if (problems.length > 0) {
  console.error(`✖ design tokens: ${problems.length} problem(s)\n${problems.map((p) => `  - ${p}`).join('\n')}`);
  process.exit(1);
}

const outputs: [string, string][] = [
  [CSS_PATH, css],
  [DOC_PATH, doc],
];
if (CHECK) {
  const stale = outputs.filter(([path, content]) => {
    try {
      return readFileSync(ROOT + path, 'utf8') !== content;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(`✖ design tokens: ${stale.map(([p]) => p).join(', ')} out of date — run \`npm run tokens\``);
    process.exit(1);
  }
  console.log('✔ design tokens: generated files are current; palette rules hold');
} else {
  for (const [path, content] of outputs) writeFileSync(ROOT + path, content);
  console.log(`✔ design tokens: wrote ${outputs.map(([p]) => p).join(', ')}`);
}
